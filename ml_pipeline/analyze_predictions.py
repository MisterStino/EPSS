#!/usr/bin/env python3
"""
Deep Analysis of LSTM Predictions
=================================

Comprehensive analysis of predictions from ml_pipeline/results/predictions/predictions_stream.nc
Generated by lstm_exp_window_eval.py

This script provides:
1. Data structure analysis
2. Prediction quality metrics
3. Temporal pattern analysis
4. CVE-specific performance
5. Forecast horizon analysis
6. Error distribution analysis
7. Model behavior insights
"""

import numpy as np
import pandas as pd
import xarray as xr
import matplotlib.pyplot as plt
import seaborn as sns
from pathlib import Path
import warnings
warnings.filterwarnings('ignore')

# Set up plotting
plt.style.use('default')
sns.set_palette("husl")


class PredictionAnalyzer:
    """Comprehensive analysis of LSTM predictions"""
    
    def __init__(self, netcdf_path: str):
        self.netcdf_path = Path(netcdf_path)
        self.ds = None
        self.load_data()
        
    def load_data(self):
        """Load and validate the NetCDF predictions file"""
        if not self.netcdf_path.exists():
            raise FileNotFoundError(f"Predictions file not found: {self.netcdf_path}")
        
        print(f"📁 Loading predictions from: {self.netcdf_path}")
        self.ds = xr.open_dataset(self.netcdf_path)
        
        print(f"✓ Loaded dataset with {len(self.ds.cve)} CVEs")
        print(f"✓ Time dimension: {len(self.ds.time[0])} timesteps")
        print(f"✓ Forecast horizon: {len(self.ds.horizon)} days")
        
    def analyze_data_structure(self):
        """Analyze the structure and completeness of the dataset"""
        print("\n" + "="*60)
        print("📊 DATA STRUCTURE ANALYSIS")
        print("="*60)
        
        # Basic dimensions
        n_cves = len(self.ds.cve)
        n_time = len(self.ds.time[0])  # Time is 2D (cve, time)
        n_horizon = len(self.ds.horizon)
        
        print(f"Dataset dimensions:")
        print(f"  • CVEs: {n_cves:,}")
        print(f"  • Timesteps: {n_time:,}")
        print(f"  • Forecast horizons: {n_horizon}")
        
        # Data variables
        print(f"\nData variables:")
        for var in self.ds.data_vars:
            shape = self.ds[var].shape
            dtype = self.ds[var].dtype
            print(f"  • {var}: {shape} ({dtype})")
        
        # Memory usage
        total_size = sum(self.ds[var].nbytes for var in self.ds.data_vars)
        print(f"\nTotal dataset size: {total_size / 1024**2:.1f} MB")
        
        # Mask analysis (data completeness)
        eval_mask = self.ds.eval_mask.values
        horizon_mask = self.ds.mask_h.values
        
        valid_timesteps = eval_mask.sum()
        valid_predictions = horizon_mask.sum()
        total_possible = eval_mask.size
        
        print(f"\nData completeness:")
        print(f"  • Valid timesteps: {valid_timesteps:,} / {total_possible:,} ({100*valid_timesteps/total_possible:.1f}%)")
        print(f"  • Valid predictions: {valid_predictions:,}")
        print(f"  • Avg timesteps per CVE: {valid_timesteps/n_cves:.1f}")
        
        return {
            'n_cves': n_cves,
            'n_time': n_time, 
            'n_horizon': n_horizon,
            'valid_timesteps': valid_timesteps,
            'valid_predictions': valid_predictions
        }
    
    def analyze_prediction_quality(self):
        """Analyze overall prediction quality metrics"""
        print("\n" + "="*60)
        print("🎯 PREDICTION QUALITY ANALYSIS")
        print("="*60)
        
        # Get valid predictions only
        pred = self.ds.pred.values
        true = self.ds.true.values
        mask_h = self.ds.mask_h.values
        mask_e = self.ds.eval_mask.values
        
        # Create combined mask
        combined_mask = mask_h * mask_e[:, :, np.newaxis]
        valid_mask = combined_mask > 0
        
        # Extract valid predictions and targets
        valid_pred = pred[valid_mask]
        valid_true = true[valid_mask]
        
        print(f"Valid predictions: {len(valid_pred):,}")
        
        # Overall metrics
        mse = np.mean((valid_pred - valid_true) ** 2)
        mae = np.mean(np.abs(valid_pred - valid_true))
        rmse = np.sqrt(mse)
        
        # Additional metrics
        correlation = np.corrcoef(valid_pred, valid_true)[0, 1]
        
        # Directional accuracy (for changes)
        if len(valid_pred) > 1:
            pred_diff = np.diff(valid_pred)
            true_diff = np.diff(valid_true)
            directional_acc = np.mean(np.sign(pred_diff) == np.sign(true_diff))
        else:
            directional_acc = 0.0
        
        print(f"Overall Performance:")
        print(f"  • MSE: {mse:.6f}")
        print(f"  • MAE: {mae:.6f}")
        print(f"  • RMSE: {rmse:.6f}")
        print(f"  • Correlation: {correlation:.4f}")
        print(f"  • Directional Accuracy: {directional_acc:.4f}")
        
        # Prediction range analysis
        print(f"\nPrediction Statistics:")
        print(f"  • Pred range: [{valid_pred.min():.4f}, {valid_pred.max():.4f}]")
        print(f"  • True range: [{valid_true.min():.4f}, {valid_true.max():.4f}]")
        print(f"  • Pred mean: {valid_pred.mean():.4f} ± {valid_pred.std():.4f}")
        print(f"  • True mean: {valid_true.mean():.4f} ± {valid_true.std():.4f}")
        
        return {
            'mse': mse, 'mae': mae, 'rmse': rmse,
            'correlation': correlation,
            'directional_accuracy': directional_acc,
            'valid_predictions': len(valid_pred)
        }
    
    def analyze_horizon_performance(self):
        """Analyze performance across different forecast horizons"""
        print("\n" + "="*60)
        print("📈 FORECAST HORIZON ANALYSIS")
        print("="*60)
        
        pred = self.ds.pred.values
        true = self.ds.true.values
        mask_h = self.ds.mask_h.values
        mask_e = self.ds.eval_mask.values
        
        horizon_metrics = []
        
        for h in range(len(self.ds.horizon)):
            # Get mask for this horizon
            h_mask = mask_h[:, :, h] * mask_e
            valid_idx = h_mask > 0
            
            if valid_idx.sum() == 0:
                continue
                
            h_pred = pred[:, :, h][valid_idx]
            h_true = true[:, :, h][valid_idx]
            
            # Calculate metrics for this horizon
            h_mse = np.mean((h_pred - h_true) ** 2)
            h_mae = np.mean(np.abs(h_pred - h_true))
            h_corr = np.corrcoef(h_pred, h_true)[0, 1] if len(h_pred) > 1 else 0
            
            horizon_metrics.append({
                'horizon': h + 1,
                'mse': h_mse,
                'mae': h_mae,
                'correlation': h_corr,
                'n_predictions': len(h_pred)
            })
        
        horizon_df = pd.DataFrame(horizon_metrics)
        
        print("Performance by forecast horizon:")
        print(horizon_df.round(4).to_string(index=False))
        
        # Analyze degradation pattern
        if len(horizon_df) > 1:
            mae_trend = np.polyfit(horizon_df.horizon, horizon_df.mae, 1)[0]
            corr_trend = np.polyfit(horizon_df.horizon, horizon_df.correlation, 1)[0]
            
            print(f"\nForecast degradation:")
            print(f"  • MAE trend: {mae_trend:.6f} per day")
            print(f"  • Correlation trend: {corr_trend:.6f} per day")
        
        return horizon_df
    
    def analyze_temporal_patterns(self):
        """Analyze temporal patterns in predictions and errors"""
        print("\n" + "="*60)
        print("📅 TEMPORAL PATTERN ANALYSIS")
        print("="*60)
        
        # Convert time coordinates to datetime
        time_coords = self.ds.time.values
        
        # Get valid data
        pred = self.ds.pred.values
        true = self.ds.true.values
        mask_e = self.ds.eval_mask.values
        
        # Calculate daily errors (horizon=1)
        daily_pred = pred[:, :, 0]  # First horizon (1-day ahead)
        daily_true = true[:, :, 0]
        daily_mask = mask_e
        
        # Create time series of daily performance
        daily_errors = []
        daily_dates = []
        
        for cve_idx in range(len(self.ds.cve)):
            cve_mask = daily_mask[cve_idx] > 0
            if cve_mask.sum() == 0:
                continue
                
            cve_times = time_coords[cve_idx][cve_mask]
            cve_pred = daily_pred[cve_idx][cve_mask]
            cve_true = daily_true[cve_idx][cve_mask]
            cve_errors = np.abs(cve_pred - cve_true)
            
            daily_dates.extend(cve_times)
            daily_errors.extend(cve_errors)
        
        # Convert to pandas for easier analysis
        if daily_dates:
            temporal_df = pd.DataFrame({
                'date': pd.to_datetime(daily_dates),
                'error': daily_errors
            })
            
            # Remove invalid dates
            temporal_df = temporal_df[temporal_df.date.notna()]
            
            if len(temporal_df) > 0:
                temporal_df = temporal_df.sort_values('date')
                
                print(f"Temporal analysis period:")
                print(f"  • Start: {temporal_df.date.min()}")
                print(f"  • End: {temporal_df.date.max()}")
                print(f"  • Duration: {(temporal_df.date.max() - temporal_df.date.min()).days} days")
                
                # Weekly patterns
                temporal_df['weekday'] = temporal_df.date.dt.day_name()
                weekly_errors = temporal_df.groupby('weekday')['error'].mean()
                
                print(f"\nWeekly error patterns:")
                for day, error in weekly_errors.items():
                    print(f"  • {day}: {error:.4f}")
                
                # Monthly patterns
                temporal_df['month'] = temporal_df.date.dt.month_name()
                monthly_errors = temporal_df.groupby('month')['error'].mean()
                
                print(f"\nMonthly error patterns (top 5):")
                top_months = monthly_errors.nlargest(5)
                for month, error in top_months.items():
                    print(f"  • {month}: {error:.4f}")
                
                return temporal_df
        
        print("No valid temporal data found for analysis")
        return None
    
    def analyze_cve_performance(self):
        """Analyze performance by individual CVEs"""
        print("\n" + "="*60)
        print("🔍 CVE-SPECIFIC PERFORMANCE ANALYSIS")
        print("="*60)
        
        pred = self.ds.pred.values
        true = self.ds.true.values
        mask_h = self.ds.mask_h.values
        mask_e = self.ds.eval_mask.values
        
        cve_metrics = []
        
        for cve_idx, cve_id in enumerate(self.ds.cve.values):
            # Get data for this CVE
            cve_pred = pred[cve_idx]
            cve_true = true[cve_idx]
            cve_mask_h = mask_h[cve_idx]
            cve_mask_e = mask_e[cve_idx]
            
            # Combined mask
            cve_mask = cve_mask_h * cve_mask_e[:, np.newaxis]
            valid_idx = cve_mask > 0
            
            if valid_idx.sum() == 0:
                continue
            
            cve_pred_valid = cve_pred[valid_idx]
            cve_true_valid = cve_true[valid_idx]
            
            # Calculate metrics
            cve_mse = np.mean((cve_pred_valid - cve_true_valid) ** 2)
            cve_mae = np.mean(np.abs(cve_pred_valid - cve_true_valid))
            cve_corr = np.corrcoef(cve_pred_valid, cve_true_valid)[0, 1] if len(cve_pred_valid) > 1 else 0
            
            # Sequence statistics
            n_timesteps = cve_mask_e.sum()
            n_predictions = valid_idx.sum()
            
            cve_metrics.append({
                'cve': cve_id,
                'mse': cve_mse,
                'mae': cve_mae,
                'correlation': cve_corr,
                'n_timesteps': n_timesteps,
                'n_predictions': n_predictions,
                'avg_pred': cve_pred_valid.mean(),
                'avg_true': cve_true_valid.mean()
            })
        
        cve_df = pd.DataFrame(cve_metrics)
        
        if len(cve_df) > 0:
            print(f"CVE performance summary:")
            print(f"  • Total CVEs analyzed: {len(cve_df)}")
            print(f"  • Avg timesteps per CVE: {cve_df.n_timesteps.mean():.1f}")
            print(f"  • Avg predictions per CVE: {cve_df.n_predictions.mean():.1f}")
            
            # Performance distribution
            print(f"\nPerformance distribution:")
            print(f"  • MAE: {cve_df.mae.mean():.4f} ± {cve_df.mae.std():.4f}")
            print(f"  • Correlation: {cve_df.correlation.mean():.4f} ± {cve_df.correlation.std():.4f}")
            
            # Best and worst performers
            print(f"\nTop 5 best performers (by MAE):")
            best = cve_df.nsmallest(5, 'mae')[['cve', 'mae', 'correlation', 'n_predictions']]
            print(best.to_string(index=False))
            
            print(f"\nTop 5 worst performers (by MAE):")
            worst = cve_df.nlargest(5, 'mae')[['cve', 'mae', 'correlation', 'n_predictions']]
            print(worst.to_string(index=False))
            
            return cve_df
        
        print("No valid CVE data found for analysis")
        return None
    
    def analyze_error_distribution(self):
        """Analyze the distribution of prediction errors"""
        print("\n" + "="*60)
        print("📊 ERROR DISTRIBUTION ANALYSIS")
        print("="*60)
        
        pred = self.ds.pred.values
        true = self.ds.true.values
        mask_h = self.ds.mask_h.values
        mask_e = self.ds.eval_mask.values
        
        # Get all valid errors
        combined_mask = mask_h * mask_e[:, :, np.newaxis]
        valid_mask = combined_mask > 0
        
        errors = pred[valid_mask] - true[valid_mask]
        abs_errors = np.abs(errors)
        
        print(f"Error statistics:")
        print(f"  • Mean error: {errors.mean():.6f}")
        print(f"  • Error std: {errors.std():.6f}")
        print(f"  • Mean absolute error: {abs_errors.mean():.6f}")
        print(f"  • Median absolute error: {np.median(abs_errors):.6f}")
        
        # Percentiles
        percentiles = [50, 75, 90, 95, 99]
        print(f"\nAbsolute error percentiles:")
        for p in percentiles:
            val = np.percentile(abs_errors, p)
            print(f"  • {p}th percentile: {val:.6f}")
        
        # Large errors analysis
        large_error_threshold = np.percentile(abs_errors, 95)
        large_errors = abs_errors > large_error_threshold
        
        print(f"\nLarge errors (>{large_error_threshold:.4f}):")
        print(f"  • Count: {large_errors.sum():,} ({100*large_errors.mean():.1f}%)")
        print(f"  • Mean: {abs_errors[large_errors].mean():.6f}")
        print(f"  • Max: {abs_errors.max():.6f}")
        
        return {
            'errors': errors,
            'abs_errors': abs_errors,
            'large_error_threshold': large_error_threshold
        }
    
    def generate_summary_report(self):
        """Generate a comprehensive summary report"""
        print("\n" + "="*60)
        print("📋 COMPREHENSIVE ANALYSIS SUMMARY")
        print("="*60)
        
        # Run all analyses
        structure = self.analyze_data_structure()
        quality = self.analyze_prediction_quality()
        horizon_df = self.analyze_horizon_performance()
        temporal_df = self.analyze_temporal_patterns()
        cve_df = self.analyze_cve_performance()
        error_analysis = self.analyze_error_distribution()
        
        # Generate summary insights
        print("\n" + "🎯 KEY INSIGHTS:")
        print("-" * 40)
        
        # Model performance assessment
        if quality['correlation'] > 0.7:
            perf_rating = "Excellent"
        elif quality['correlation'] > 0.5:
            perf_rating = "Good"
        elif quality['correlation'] > 0.3:
            perf_rating = "Fair"
        else:
            perf_rating = "Poor"
        
        print(f"1. Overall Performance: {perf_rating}")
        print(f"   • Correlation: {quality['correlation']:.3f}")
        print(f"   • MAE: {quality['mae']:.4f}")
        print(f"   • Directional accuracy: {quality['directional_accuracy']:.3f}")
        
        # Forecast horizon insights
        if len(horizon_df) > 1:
            best_horizon = horizon_df.loc[horizon_df.mae.idxmin(), 'horizon']
            worst_horizon = horizon_df.loc[horizon_df.mae.idxmax(), 'horizon']
            print(f"\n2. Forecast Horizon Performance:")
            print(f"   • Best horizon: Day {best_horizon}")
            print(f"   • Worst horizon: Day {worst_horizon}")
            print(f"   • Performance degrades with longer horizons: {'Yes' if horizon_df.mae.is_monotonic_increasing else 'No'}")
        
        # Data coverage insights
        coverage = structure['valid_timesteps'] / (structure['n_cves'] * structure['n_time'])
        print(f"\n3. Data Coverage:")
        print(f"   • Overall coverage: {coverage:.1%}")
        print(f"   • Avg timesteps per CVE: {structure['valid_timesteps']/structure['n_cves']:.1f}")
        
        # CVE performance insights
        if cve_df is not None and len(cve_df) > 0:
            high_perf_cves = (cve_df.correlation > 0.5).sum()
            print(f"\n4. CVE-Level Performance:")
            print(f"   • High-performing CVEs (corr > 0.5): {high_perf_cves}/{len(cve_df)} ({100*high_perf_cves/len(cve_df):.1f}%)")
            print(f"   • Performance variation (MAE std): {cve_df.mae.std():.4f}")
        
        # Error distribution insights
        if error_analysis:
            error_skew = abs(error_analysis['errors'].mean()) / error_analysis['errors'].std()
            print(f"\n5. Error Characteristics:")
            print(f"   • Error bias: {'Low' if error_skew < 0.1 else 'Moderate' if error_skew < 0.3 else 'High'}")
            print(f"   • Error distribution: {'Symmetric' if abs(error_analysis['errors'].mean()) < 0.001 else 'Skewed'}")
        
        print("\n" + "="*60)
        print("Analysis complete! 🎉")
        
        return {
            'structure': structure,
            'quality': quality,
            'horizon_df': horizon_df,
            'temporal_df': temporal_df,
            'cve_df': cve_df,
            'error_analysis': error_analysis
        }


def main():
    """Main analysis function"""
    netcdf_path = "ml_pipeline/results/predictions/predictions_stream.nc"
    
    if not Path(netcdf_path).exists():
        print(f"❌ Predictions file not found: {netcdf_path}")
        print("Please run the LSTM training script first to generate predictions.")
        return
    
    print("🔍 DEEP ANALYSIS OF LSTM PREDICTIONS")
    print("=" * 60)
    
    analyzer = PredictionAnalyzer(netcdf_path)
    results = analyzer.generate_summary_report()
    
    # Save results summary
    if results['cve_df'] is not None:
        results['cve_df'].to_csv("ml_pipeline/results/cve_performance_analysis.csv", index=False)
        print(f"\n💾 CVE performance analysis saved to: ml_pipeline/results/cve_performance_analysis.csv")
    
    if results['horizon_df'] is not None:
        results['horizon_df'].to_csv("ml_pipeline/results/horizon_performance_analysis.csv", index=False)
        print(f"💾 Horizon performance analysis saved to: ml_pipeline/results/horizon_performance_analysis.csv")


if __name__ == "__main__":
    main() 